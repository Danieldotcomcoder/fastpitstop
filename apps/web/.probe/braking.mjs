import { chromium } from '@playwright/test';
const OUT = process.env.SP;
const browser = await chromium.launch();
const page = await browser.newPage({ viewport: { width: 1500, height: 1200 } });
const errs = [];
page.on('pageerror', (e) => errs.push('[pageerror] ' + String(e).slice(0, 300)));
page.on('console', (m) => { if (m.type() === 'error') errs.push('[console] ' + m.text().slice(0, 300)); });
await page.goto('http://127.0.0.1:4400/sessions/2024/1?speed=400', { waitUntil: 'domcontentloaded' });
await page.waitForTimeout(70000);
console.log('LAP:', await page.getByTestId('session-lap').textContent().catch(() => '?'));
await page.getByRole('button', { name: /Braking/ }).click();
await page.waitForTimeout(20000);
console.log('--- BRAKING ---');
console.log((await page.locator('.stage-content').innerText()).slice(0, 1400));
await page.locator('.corner-map button').first().click().catch(() => {});
await page.waitForTimeout(1000);
await page.screenshot({ path: `${OUT}/braking-new.png`, fullPage: true });
console.log('ERRORS:', errs.slice(0, 8).join('\n') || 'none');
await browser.close();
