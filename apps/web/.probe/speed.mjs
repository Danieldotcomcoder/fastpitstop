import { chromium } from '@playwright/test';
const browser = await chromium.launch();
const page = await browser.newPage({ viewport: { width: 1400, height: 1000 } });
const sockets = [];
page.on('websocket', (ws) => sockets.push(ws.url()));
const errs = [];
page.on('pageerror', (e) => errs.push(String(e).slice(0, 200)));
await page.goto('http://127.0.0.1:4400/sessions/2024/1?speed=20', { waitUntil: 'domcontentloaded' });
await page.waitForTimeout(12000);
console.log('after load:', sockets.length, 'socket(s)');
await page.getByLabel('Replay speed').selectOption('50');
await page.waitForTimeout(8000);
console.log('after speed change:', sockets.length, 'socket(s) total');
sockets.forEach((u, i) => console.log(`  ${i + 1}: ${u.split('?')[1]}`));
await page.getByRole('button', { name: /Restart/ }).click();
await page.waitForTimeout(6000);
console.log('after restart:', sockets.length, 'socket(s) total');
console.log('ERRORS:', errs.join(' | ') || 'none');
await browser.close();
