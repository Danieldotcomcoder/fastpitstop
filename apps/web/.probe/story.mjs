import { chromium } from '@playwright/test';
const OUT = process.env.SP;
const browser = await chromium.launch();
const page = await browser.newPage({ viewport: { width: 1500, height: 1300 } });
const errs = [];
page.on('pageerror', (e) => errs.push('[pageerror] ' + String(e).slice(0, 300)));
page.on('console', (m) => { if (m.type() === 'error') errs.push('[console] ' + m.text().slice(0, 300)); });
await page.goto('http://127.0.0.1:4400/sessions/2024/1?speed=400', { waitUntil: 'domcontentloaded' });
await page.waitForTimeout(8000);
await page.getByRole('button', { name: /Race story/ }).click();
await page.waitForTimeout(12000);
console.log('--- STORY (early, should be gated) ---');
console.log((await page.locator('.stage-content').innerText()).slice(0, 600));
await page.waitForTimeout(60000);
console.log('\n--- STORY (later) ---');
console.log((await page.locator('.stage-content').innerText()).slice(0, 1200));
await page.screenshot({ path: `${OUT}/story-tab.png`, fullPage: true });
console.log('ERRORS:', errs.slice(0, 8).join('\n') || 'none');
await browser.close();
