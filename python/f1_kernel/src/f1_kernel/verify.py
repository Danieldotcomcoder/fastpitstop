"""Phase 2 verification harness (`just verify-phase2`).

Runs the unified kernel (`analyze_session`) end-to-end over the checked-in
synthetic fixture — the same two races `python/f1_kernel/tests/` uses,
generated by `python/f1_kernel/fixtures/generate.py` — and asserts the
release-gate exit criteria from CLAUDE.md's Phase 2 prompt:

1. the kernel runs over a full session with no crash;
2. the clean-lap filter's SC/pit/dirty-air exclusions match the fixture's
   own ground truth (`tests/fixtures/truth.json`) — spot-checking correctness
   the same way `tests/test_cleaning.py` does, just from the top-level API;
3. the fuel coefficient and the cross-circuit default pit loss are
   CALIBRATED, not hardcoded (`KernelParams.PARAM_PROVENANCE`), and at
   least one shipped circuit carries its own calibrated value;
4. degradation is directionally sane (softer compounds degrade faster)
   and (5) the undercut predictor clears its calibration check over at
   least 5 held-out 2025 races — both asserted against the COMMITTED
   backtest reports (`reports/degradation_backtest.md`,
   `reports/undercut_backtest.md`), because confirming those claims from
   scratch needs the real 2023-2025 backfill this repo does not ship
   (`data/` is gitignored) — see docs/PHASE2.md's three-layer testing
   discipline. Re-run `tools/run_backtest_suite.py` against a populated
   `data/historical/` to refresh those reports; this harness only checks
   that the checked-in ones still say what they say.

Runs green in CI with no data, no database and no network: everything here
reads either the checked-in synthetic fixture or the checked-in report
files, never `data/historical/` itself.
"""

from __future__ import annotations

import json
import re
import sys
from pathlib import Path
from typing import Any

from f1_domain import SessionKey, SessionType
from f1_kernel.circuit import list_circuits, load_circuit
from f1_kernel.params import PARAM_PROVENANCE, KernelParams, ParamProvenance
from f1_kernel.report import KernelReport, analyze_session
from f1_kernel.sources import HistoricalSource

PACKAGE_ROOT = Path(__file__).resolve().parents[2]
FIXTURE_ROOT = PACKAGE_ROOT / "tests" / "fixtures" / "historical"
TRUTH_PATH = PACKAGE_ROOT / "tests" / "fixtures" / "truth.json"
REPORTS_DIR = PACKAGE_ROOT / "reports"

SC_RACE = SessionKey(year=2024, round=1, session_type=SessionType.RACE)
GREEN_RACE = SessionKey(year=2024, round=2, session_type=SessionType.RACE)

MIN_2025_RACES_FOR_MILESTONE = 5
"""CLAUDE.md's Phase 2 milestone: the undercut predictor must clear its
calibration check on at least this many replayed 2025 races."""


class VerificationError(AssertionError):
    """A Phase 2 exit criterion did not hold."""


def load_truth() -> dict[str, Any]:
    return json.loads(TRUTH_PATH.read_text(encoding="utf-8"))


def truth_key(session_key: SessionKey) -> str:
    return f"{session_key.year}_{session_key.round:02d}_Race"


def _laps_where(report: KernelReport, column: str) -> dict[str, list[int]]:
    hits = report.annotated_laps.filter(column).sort("driver", "lap_number")
    result: dict[str, list[int]] = {}
    for driver, lap_number in zip(hits["driver"], hits["lap_number"], strict=True):
        result.setdefault(str(driver), []).append(int(lap_number))
    return result


def _as_str_list_map(value: object) -> dict[str, list[int]]:
    assert isinstance(value, dict)
    return {str(k): [int(x) for x in v] for k, v in value.items()}  # type: ignore[union-attr]


def verify(*, fixture_root: Path = FIXTURE_ROOT) -> list[str]:
    """Run every Phase 2 exit-criterion check. Returns human-readable lines
    on success; raises `VerificationError` on the first collected failure."""
    failures: list[str] = []

    def check(name: str, actual: object, want: object) -> None:
        if actual != want:
            failures.append(f"{name}:\n    expected {want!r}\n    got      {actual!r}")

    # 1. The kernel runs end-to-end, over more than one session, no crash.
    source = HistoricalSource(fixture_root)
    params = KernelParams()
    reports: dict[SessionKey, KernelReport] = {}
    for key in (SC_RACE, GREEN_RACE):
        reports[key] = analyze_session(source, key, params)

    sc_report = reports[SC_RACE]
    green_report = reports[GREEN_RACE]
    for label, report in (("SC_RACE", sc_report), ("GREEN_RACE", green_report)):
        if report.frames.laps.is_empty():
            failures.append(f"{label}: analyze_session produced no laps at all")
        if not report.degradation_fits:
            failures.append(f"{label}: analyze_session produced no degradation fits")

    # 2. Clean-lap filter correctness, against the fixture's own ground truth.
    truth = load_truth()
    sc_truth = truth[truth_key(SC_RACE)]
    check(
        "SC_RACE sc_laps_by_driver",
        _laps_where(sc_report, "is_sc"),
        _as_str_list_map(sc_truth["sc_laps_by_driver"]),
    )
    check(
        "SC_RACE dirty_air_laps",
        _laps_where(sc_report, "is_dirty_air"),
        _as_str_list_map(sc_truth["dirty_air_laps"]),
    )
    check(
        "SC_RACE pit_in_laps (is_in_lap)",
        _laps_where(sc_report, "is_in_lap"),
        _as_str_list_map(sc_truth["pit_in_laps"]),
    )
    green_truth = truth[truth_key(GREEN_RACE)]
    check(
        "GREEN_RACE yellow_laps_by_driver",
        _laps_where(green_report, "is_yellow"),
        _as_str_list_map(green_truth["yellow_laps_by_driver"]),
    )

    # 3. Fuel coefficient and default pit loss are CALIBRATED, not hardcoded.
    check(
        "fuel_coef_s_per_kg provenance",
        PARAM_PROVENANCE["fuel_coef_s_per_kg"],
        ParamProvenance.CALIBRATED,
    )
    check(
        "default_pit_loss_s provenance",
        PARAM_PROVENANCE["default_pit_loss_s"],
        ParamProvenance.CALIBRATED,
    )
    calibrated_circuits = [
        circuit_id
        for circuit_id in list_circuits()
        if load_circuit(circuit_id).pit_loss_provenance == "calibrated"
    ]
    if not calibrated_circuits:
        failures.append("no shipped circuit file has a calibrated pit_loss_provenance")

    # 4. Degradation is directionally sane, per the committed backtest report.
    degradation_report = _read_report("degradation_backtest.md")
    if degradation_report is None:
        failures.append(
            "reports/degradation_backtest.md is missing — run "
            "tools/backtest_degradation.py (or run_backtest_suite.py) against a "
            "populated data/historical/ and commit its output"
        )
    elif "Directional (softer compounds degrade faster, by median): **PASS**" not in (
        degradation_report
    ):
        failures.append(
            "reports/degradation_backtest.md does not report a PASS on directional sanity"
        )

    # 5. THE MILESTONE: undercut calibration PASS over >= 5 held-out 2025 races.
    n_2025_races = 0
    undercut_report = _read_report("undercut_backtest.md")
    if undercut_report is None:
        failures.append(
            "reports/undercut_backtest.md is missing — run tools/backtest_undercut.py "
            "(or run_backtest_suite.py) against a populated data/historical/ and commit "
            "its output"
        )
    else:
        n_2025_races = len(re.findall(r"^- 2025 R\d+ race\b", undercut_report, re.MULTILINE))
        if n_2025_races < MIN_2025_RACES_FOR_MILESTONE:
            failures.append(
                f"undercut_backtest.md's corpus has {n_2025_races} 2025 race(s), fewer than "
                f"the milestone's {MIN_2025_RACES_FOR_MILESTONE}"
            )
        if "**PASS**" not in undercut_report:
            failures.append(
                "undercut_backtest.md's calibration check is not PASS "
                "(high-confidence hit rate must beat low-confidence)"
            )

    if failures:
        raise VerificationError("Phase 2 verification failed:\n" + "\n".join(failures))

    return [
        "PHASE 2 VERIFY: OK",
        f"  kernel ran end-to-end over {len(reports)} fixture session(s), no crash",
        "  clean-lap filter (SC/dirty-air/pit/yellow) matches fixture ground truth",
        "  fuel_coef_s_per_kg + default_pit_loss_s are CALIBRATED "
        f"({len(calibrated_circuits)} circuit file(s) calibrated: "
        f"{', '.join(calibrated_circuits)})",
        "  degradation_backtest.md: directional sanity PASS",
        f"  undercut_backtest.md: calibration PASS over {n_2025_races} held-out 2025 race(s)",
    ]


def _read_report(name: str) -> str | None:
    path = REPORTS_DIR / name
    return path.read_text(encoding="utf-8") if path.is_file() else None


def main() -> int:
    try:
        for line in verify():
            print(line)
    except VerificationError as exc:
        print(str(exc), file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
