"""The undercut/overcut backtest CLAUDE.md's Prompt 2.5 asks for: predict
every real green-flag stop at the lap BEFORE it happened, using only data
available up to that lap, and score the call against what actually
happened — a hit/miss table, split by confidence, so a "low confidence"
wrong call is visibly different from a "high confidence" wrong call.

    uv run python python/f1_kernel/tools/backtest_undercut.py --seasons 2025
    uv run python python/f1_kernel/tools/backtest_undercut.py --seasons 2024 2025

This is reporting, not calibration: nothing here is written back into
`KernelParams` or the circuit files (that is `calibrate_pit_loss.py`).
Re-running it never changes kernel behaviour, only
`python/f1_kernel/reports/undercut_backtest.md`.

Dev-only: needs `data/historical/` populated for the requested season(s).
Never imported by the kernel at runtime.
"""

from __future__ import annotations

import argparse
import sys
from collections.abc import Sequence
from pathlib import Path

import polars as pl

from f1_domain import SessionType
from f1_kernel.backtest import Backtest
from f1_kernel.params import KernelParams
from f1_kernel.sources import HistoricalSource, list_historical_sessions
from f1_kernel.undercut_eval import evaluate_session_stops_rows

DEFAULT_ROOT = Path(__file__).parents[3] / "data" / "historical"
OUTPUT_PATH = Path(__file__).parents[1] / "reports" / "undercut_backtest.md"
DEFAULT_SEASONS = (2025,)


def main(argv: list[str]) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", default=str(DEFAULT_ROOT), help="historical backfill root")
    parser.add_argument(
        "--seasons",
        type=int,
        nargs="+",
        default=list(DEFAULT_SEASONS),
        help="seasons to include (default: 2025, the held-out prediction season)",
    )
    parser.add_argument("--out", default=str(OUTPUT_PATH))
    args = parser.parse_args(argv[1:])

    source = HistoricalSource(args.root)
    races = [
        ref
        for ref in list_historical_sessions(args.root, seasons=args.seasons)
        if ref.session_key.session_type is SessionType.RACE
    ]
    if not races:
        print(
            f"no backfilled races found under {args.root} for seasons {args.seasons}; "
            "run `uv run f1-backfill --season <year>` first",
            file=sys.stderr,
        )
        return 1

    labels = [f"{ref.label} ({ref.event_name})" for ref in races]
    print(f"backtesting undercut/overcut over {len(races)} race(s):")
    for label in labels:
        print(f"  {label}")
    bt = Backtest(source, params=KernelParams())
    result = bt.run(evaluate_session_stops_rows, races, raise_on_error=False)

    print(result.summary())
    if result.errors:
        print(f"\n{len(result.errors)} session(s) failed:")
        for error in result.errors:
            print(f"  {error}")

    table = result.table
    report = _render_report(labels, result.errors, table)
    out_path = Path(args.out)
    out_path.parent.mkdir(parents=True, exist_ok=True)
    out_path.write_text(report, encoding="utf-8")
    print(f"\nwrote {out_path}")

    evaluated = table.filter(pl.col("evaluated")) if not table.is_empty() else table
    scored = (
        evaluated.filter(pl.col("hit").is_not_null()) if not evaluated.is_empty() else evaluated
    )
    if not scored.is_empty():
        hit_rate = float(scored["hit"].cast(pl.Float64).mean())  # type: ignore[arg-type]
        print(f"\noverall hit rate: {hit_rate:.1%} over {scored.height} scored call(s)")
    return 0


def _render_report(labels: Sequence[str], errors: Sequence[object], table: pl.DataFrame) -> str:
    lines = [
        "# Undercut / overcut backtest report",
        "",
        f"Generated by `python/f1_kernel/tools/backtest_undercut.py` over {len(labels)} race(s).",
        "Predictions are made at the lap BEFORE the real stop, from data available up to that "
        "lap only (degradation refitted on the slice each time) — see "
        "`f1_kernel.undercut_eval` for the walk-forward contract and exclusion rules. "
        "Re-run the tool as more of the season lands in the backfill.",
        "",
        "## Corpus",
        "",
        *[f"- {label}" for label in labels],
        "",
    ]
    if errors:
        lines += ["## Session failures", ""]
        lines += [f"- {error}" for error in errors]
        lines.append("")

    if table.is_empty():
        lines += ["_no stop-pairs found at all._", ""]
        return "\n".join(lines)

    evaluated = table.filter(pl.col("evaluated"))
    excluded = table.filter(~pl.col("evaluated"))
    scored = evaluated.filter(pl.col("hit").is_not_null())
    no_call = evaluated.filter(pl.col("hit").is_null())

    lines += [
        "## Coverage",
        "",
        f"- Stop-pairs discovered: **{table.height}**",
        f"- Excluded (not a scoreable green-flag duel): **{excluded.height}**",
        f"- Evaluated (a green-flag duel with a known outcome): **{evaluated.height}**",
        f"  - Scored (window not UNKNOWN): **{scored.height}**",
        f"  - No-call (inputs too thin — `window=unknown`): **{no_call.height}**",
        "",
    ]
    if not excluded.is_empty():
        lines += ["### Exclusion reasons", ""]
        reason_counts = (
            excluded.group_by("exclusion").agg(pl.len().alias("n")).sort("n", descending=True)
        )
        lines.append("| reason | count |")
        lines.append("| --- | --- |")
        for row in reason_counts.to_dicts():
            lines.append(f"| {row['exclusion']} | {row['n']} |")
        lines.append("")

    if not scored.is_empty():
        lines += ["## Hit rate by confidence", ""]
        lines.append(_confidence_table(scored))
        lines.append("")
        lines += ["## Hit rate by kind", ""]
        lines.append(_kind_table(scored))
        lines.append("")
        lines += [
            "## Calibration check",
            "",
            "A well-calibrated predictor's HIGH-confidence hit rate should exceed its "
            "LOW-confidence hit rate — the whole point of reporting confidence at all.",
            "",
            _calibration_verdict(scored),
            "",
        ]
        lines += ["## Worst misses (highest confidence, wrong call)", ""]
        lines.append(_worst_misses_table(scored))
        lines.append("")

    return "\n".join(lines)


def _confidence_table(scored: pl.DataFrame) -> str:
    grouped = (
        scored.group_by("confidence")
        .agg(
            pl.len().alias("n"),
            pl.col("hit").cast(pl.Float64).mean().alias("hit_rate"),
        )
        .sort("confidence")
    )
    lines = ["| confidence | n | hit rate |", "| --- | --- | --- |"]
    for row in grouped.to_dicts():
        lines.append(f"| {row['confidence']} | {row['n']} | {row['hit_rate']:.1%} |")
    return "\n".join(lines)


def _kind_table(scored: pl.DataFrame) -> str:
    grouped = (
        scored.group_by("kind")
        .agg(
            pl.len().alias("n"),
            pl.col("hit").cast(pl.Float64).mean().alias("hit_rate"),
        )
        .sort("kind")
    )
    lines = ["| kind | n | hit rate |", "| --- | --- | --- |"]
    for row in grouped.to_dicts():
        lines.append(f"| {row['kind']} | {row['n']} | {row['hit_rate']:.1%} |")
    return "\n".join(lines)


def _calibration_verdict(scored: pl.DataFrame) -> str:
    rates: dict[str, float] = {}
    for level in ("low", "medium", "high"):
        subset = scored.filter(pl.col("confidence") == level)
        if not subset.is_empty():
            rates[level] = float(subset["hit"].cast(pl.Float64).mean())  # type: ignore[arg-type]
    if "high" in rates and "low" in rates:
        verdict = "PASS" if rates["high"] >= rates["low"] else "FAIL"
        return f"**{verdict}**: high={rates['high']:.1%} vs low={rates['low']:.1%}"
    return f"insufficient confidence spread to check ({sorted(rates)})"


def _worst_misses_table(scored: pl.DataFrame) -> str:
    confidence_rank = pl.col("confidence").replace_strict(
        {"high": 2, "medium": 1, "low": 0}, default=-1
    )
    misses = (
        scored.filter(~pl.col("hit"))
        .with_columns(confidence_rank.alias("_rank"))
        .sort(by=["_rank", "gap_at_decision_s"], descending=[True, False])
        .drop("_rank")
    )
    if misses.is_empty():
        return "_no misses._"
    lines = [
        "| kind | attacker | defender | decision_lap | confidence | predicted_margin_s | "
        "actual_margin_s | window | crossover_lap |",
        "| --- | --- | --- | --- | --- | --- | --- | --- | --- |",
    ]
    for row in misses.head(20).to_dicts():
        predicted = _fmt(row["predicted_margin_s"])
        actual = _fmt(row["actual_margin_s"])
        lines.append(
            f"| {row['kind']} | {row['attacker']} | {row['defender']} | {row['decision_lap']} "
            f"| {row['confidence']} | {predicted} | {actual} "
            f"| {row['window']} | {row['crossover_lap']} |"
        )
    return "\n".join(lines)


def _fmt(value: float | None) -> str:
    return f"{value:.2f}" if value is not None else "n/a"


if __name__ == "__main__":
    raise SystemExit(main(sys.argv))
