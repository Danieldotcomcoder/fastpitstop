"""DB-free radio-corpus fixture loading — Phase 4.5's `just verify-phase4`
needs a REAL running `f1_api` process (Playwright drives a real browser
against it, the same "no data, no database, no network" discipline every
other `verify-phaseN` harness already follows) to answer `/radio/search`,
`/sessions/{key}/radio` and the `/stream/{key}` `radio_clip` envelope with
real, ranked, context-enriched data — but the radio corpus otherwise has NO
DB-free real backing at all (`f1_api.radio`'s own module docstring), unlike
historical sessions.

`F1_API_RADIO_FIXTURE`, when set to a checked-in JSON file's path
(`python/f1_radio/tests/fixtures/e2e_radio_fixture.json`, regenerated by
`python/f1_radio/fixtures/generate_e2e.py`), makes `f1_api.radio`'s
dependency providers load a `MemorySearchIndex`/`MemoryTranscriptStore`
seeded from it instead of opening Postgres — the exact same fakes
`test_radio.py` already swaps in via `app.dependency_overrides`, just
reachable by an external process through an env var instead of a test-only
lever. `FixtureEmbeddingBackend` is the fixture's own scripted stand-in for
a real `sentence-transformers` model (mirroring `test_radio.py`'s own
`_FakeEmbeddingBackend`): it maps a handful of KNOWN paraphrase queries to
hand-picked vectors close to one clip's own planted embedding, proving the
search PLUMBING (query -> embed -> rank -> API -> render) end-to-end
without downloading a real model in CI — genuine semantic ranking is
already proven at the unit level (`f1_radio/tests/test_search.py`,
`test_real_embeddings.py`), which is not this harness's job to re-prove.
"""

from __future__ import annotations

import json
from collections.abc import Sequence
from dataclasses import dataclass
from datetime import datetime
from pathlib import Path
from typing import Any

from f1_domain import SessionKey, SessionType
from f1_radio.store import TranscriptRecord


@dataclass(frozen=True, slots=True)
class RadioFixture:
    records: tuple[TranscriptRecord, ...]
    query_embeddings: dict[str, list[float]]
    default_query_embedding: list[float]


def _record_from_json(session_key: SessionKey, raw: dict[str, Any]) -> TranscriptRecord:
    captured_raw = raw.get("captured_at")
    return TranscriptRecord(
        session_key=session_key,
        driver=raw.get("driver"),
        captured_at=datetime.fromisoformat(captured_raw) if captured_raw else None,
        audio_path=raw.get("audio_path", ""),
        transcript_text=raw.get("transcript_text"),
        language=raw.get("language"),
        confidence=raw.get("confidence"),
        model_version=raw.get("model_version", "fixture"),
        segments=raw.get("segments"),
        embedding=raw.get("embedding"),
        embedding_model_version=raw.get("embedding_model_version"),
        lap_number=raw.get("lap_number"),
        position=raw.get("position"),
        track_status=raw.get("track_status"),
        track_status_flags=raw.get("track_status_flags"),
    )


def load_radio_fixture(path: Path | str) -> RadioFixture:
    """Parse the checked-in fixture JSON into `TranscriptRecord`s plus the
    query-embedding lookup `FixtureEmbeddingBackend` needs. Re-read (not
    cached) on every call — the file is a few KB, and this keeps the loader
    honest about always reflecting what's on disk right now, the same
    simplicity `f1_kernel`'s own fixture readers favor over a caching layer
    that would only pay for itself at a real corpus's size."""
    data = json.loads(Path(path).read_text(encoding="utf-8"))
    session_raw = data["session_key"]
    session_key = SessionKey(
        year=session_raw["year"],
        round=session_raw["round"],
        session_type=SessionType(session_raw["session_type"]),
    )
    records = tuple(_record_from_json(session_key, clip) for clip in data["clips"])
    return RadioFixture(
        records=records,
        query_embeddings={
            str(query): [float(v) for v in vector]
            for query, vector in data.get("query_embeddings", {}).items()
        },
        default_query_embedding=[float(v) for v in data.get("default_query_embedding", [0.0])],
    )


@dataclass(frozen=True, slots=True)
class FixtureEmbeddingBackend:
    """A scripted `EmbeddingBackend` stand-in — see this module's docstring
    for why a fixture-mode search doesn't need (and deliberately avoids
    downloading) a real model."""

    query_embeddings: dict[str, list[float]]
    default: list[float]

    def encode(self, texts: Sequence[str]) -> list[list[float]]:
        return [self.query_embeddings.get(text, self.default) for text in texts]


__all__ = ["FixtureEmbeddingBackend", "RadioFixture", "load_radio_fixture"]
